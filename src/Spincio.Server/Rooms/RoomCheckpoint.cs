using System.Buffers.Text;
using System.IO.Compression;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Spincio.Engine;

namespace Spincio.Server.Rooms;

/// <summary>
/// Everything needed to rebuild a started room after the server restarts (ADR 0017): the seed and the commands
/// (ADR 0003), the salt for the final reveal, and the seats with their secret tokens.
/// </summary>
public sealed record RoomCheckpoint(
    string Code,
    ulong Seed,
    string Salt,
    IReadOnlyList<CheckpointSeat> Seats,
    IReadOnlyList<string> Log,
    GameVariant Variant = GameVariant.Spincio);

public sealed record CheckpointSeat(string Name, string? Token, bool IsBot);

/// <summary>
/// Seals checkpoints so that only a server holding the same key can read them: compressed JSON, encrypted and
/// authenticated with AES-GCM. Players keep the sealed text and hand it back after a restart; they cannot read the
/// seed, the other players' tokens or change a move.
/// </summary>
public sealed class CheckpointProtector
{
    private const string Prefix = "c1.";
    private const int NonceSize = 12;
    private const int TagSize = 16;
    private static readonly byte[] Purpose = "spincio-room-checkpoint-v1"u8.ToArray();
    private readonly byte[] _key;

    /// <param name="secret">
    /// Any text (e.g. generated by the hosting); the key is its SHA-256. Without one, a random key is used and the
    /// checkpoints only work until this process stops.
    /// </param>
    public CheckpointProtector(string? secret)
    {
        HasStableKey = !string.IsNullOrEmpty(secret);
        _key = HasStableKey ? SHA256.HashData(Encoding.UTF8.GetBytes(secret!)) : RandomNumberGenerator.GetBytes(32);
    }

    public bool HasStableKey { get; }

    public string Protect(RoomCheckpoint checkpoint)
    {
        using var compressed = new MemoryStream();
        using (var brotli = new BrotliStream(compressed, CompressionLevel.Fastest, leaveOpen: true))
        {
            JsonSerializer.Serialize(brotli, checkpoint);
        }

        byte[] plain = compressed.ToArray();
        byte[] sealedBytes = new byte[NonceSize + TagSize + plain.Length];
        var nonce = sealedBytes.AsSpan(0, NonceSize);
        RandomNumberGenerator.Fill(nonce);
        using var aes = new AesGcm(_key, TagSize);
        aes.Encrypt(nonce, plain, sealedBytes.AsSpan(NonceSize + TagSize), sealedBytes.AsSpan(NonceSize, TagSize), Purpose);
        return Prefix + Base64Url.EncodeToString(sealedBytes);
    }

    /// <summary>The checkpoint, or null if the text was not sealed with this key, was changed, or is not a checkpoint.</summary>
    public RoomCheckpoint? Unprotect(string? text)
    {
        if (text is null || !text.StartsWith(Prefix, StringComparison.Ordinal))
        {
            return null;
        }

        try
        {
            byte[] sealedBytes = Base64Url.DecodeFromChars(text.AsSpan(Prefix.Length));
            if (sealedBytes.Length < NonceSize + TagSize)
            {
                return null;
            }

            byte[] plain = new byte[sealedBytes.Length - NonceSize - TagSize];
            using var aes = new AesGcm(_key, TagSize);
            aes.Decrypt(
                sealedBytes.AsSpan(0, NonceSize), sealedBytes.AsSpan(NonceSize + TagSize), sealedBytes.AsSpan(NonceSize, TagSize), plain, Purpose);
            using var brotli = new BrotliStream(new MemoryStream(plain), CompressionMode.Decompress);
            return JsonSerializer.Deserialize<RoomCheckpoint>(brotli);
        }
        catch (Exception e) when (e is FormatException or CryptographicException or JsonException or InvalidDataException)
        {
            return null;
        }
    }
}
